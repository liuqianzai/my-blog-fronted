    luckLevel: 'supreme',
    luckTitle: '大吉 · 刚柔并济',
    interpretation: '阴阳相合，中正通达。以德立身，顺天应人，笃行致远。',
    yi: '坚守正道、沉潜笃行、诚以待人、规划长远',
